import streamlit as st
import time
import sys
import os

# Add root directory to path to allow absolute imports
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.predict import ForestFirePredictor

st.set_page_config(page_title="Forest Fire Predictor", page_icon="🔥", layout="centered")

# Custom CSS for styling
st.markdown("""
<style>
    .stButton>button {
        width: 100%;
        background-color: #ff4b4b;
        color: white;
        font-weight: bold;
        border-radius: 8px;
    }
    .stButton>button:hover {
        background-color: #ff3333;
    }
    .disclaimer {
        padding: 10px;
        background-color: rgba(255, 75, 75, 0.1);
        border-left: 5px solid #ff4b4b;
        margin-bottom: 25px;
    }
</style>
""", unsafe_allow_html=True)

@st.cache_resource
def load_predictor():
    return ForestFirePredictor()

try:
    predictor = load_predictor()
except Exception as e:
    st.error(f"Failed to load models. Ensure you have run the training scripts in `src/`. Error: {e}")
    st.stop()

st.title("🔥 Forest Fire Predictor")
st.markdown("Predict the likelihood of a forest fire and the estimated burned area based on meteorological conditions.")

st.markdown("""
<div class="disclaimer">
    <strong>⚠️ Important Disclaimer:</strong><br/>
    This predictive model was trained on the <strong>UCI Forest Fires Dataset</strong>, which represents meteorological and environmental conditions from the Montesinho Nature Park in the Trás-os-Montes region of <strong>northeast Portugal</strong>. Predictions generated by this tool reflect patterns specific to that region and <strong>may not generalize accurately to other environments, geographies, or climates.</strong>
</div>
""", unsafe_allow_html=True)

st.header("Input Parameters")
st.markdown("Please provide the relevant environmental and weather metrics:")

col1, col2 = st.columns(2)

with col1:
    st.subheader("Spatial & Temporal")
    X = st.number_input("X Coordinate (1-9)", min_value=1, max_value=9, value=5)
    Y = st.number_input("Y Coordinate (1-9)", min_value=1, max_value=9, value=5)
    month = st.selectbox("Month (1=Jan, 12=Dec)", options=list(range(1, 13)), index=7)
    day = st.selectbox("Day of Week (1=Mon, 7=Sun)", options=list(range(1, 8)), index=4)

    st.subheader("Meteorological")
    temp = st.number_input("Temperature (°C)", min_value=-10.0, max_value=45.0, value=20.0)
    RH = st.number_input("Relative Humidity (%)", min_value=0, max_value=100, value=50)
    wind = st.number_input("Wind Speed (km/h)", min_value=0.0, max_value=20.0, value=5.0)
    rain = st.number_input("Outside Rain (mm/m2)", min_value=0.0, max_value=10.0, value=0.0)

with col2:
    st.subheader("FWI System Components")
    st.caption("Forest Fire Weather Index details:")
    FFMC = st.number_input("FFMC (Fine Fuel Moisture Code)", min_value=18.0, max_value=100.0, value=85.0)
    DMC = st.number_input("DMC (Duff Moisture Code)", min_value=1.0, max_value=300.0, value=110.0)
    DC = st.number_input("DC (Drought Code)", min_value=7.0, max_value=900.0, value=500.0)
    ISI = st.number_input("ISI (Initial Spread Index)", min_value=0.0, max_value=60.0, value=8.0)

st.markdown("---")

if st.button("Predict Fire Risk & Area"):
    with st.spinner('Analyzing patterns and calculating risk...'):
        time.sleep(1) # subtle UI effect
        
        input_data = {
            'X': X, 'Y': Y, 'month': month, 'day': day, 
            'FFMC': FFMC, 'DMC': DMC, 'DC': DC, 'ISI': ISI, 
            'temp': temp, 'RH': RH, 'wind': wind, 'rain': rain
        }
        
        try:
            results = predictor.predict(input_data)
            prob = results['fire_probability']
            area_pred = results['estimated_area_burned_ha']
            
            st.subheader("Prediction Results")
            res_col1, res_col2 = st.columns(2)
            res_col1.metric("Likelihood of Fire", f"{prob * 100:.1f} %", "Probability of occurrence", delta_color="off")
            
            if prob > 0.5:
                res_col2.metric("Estimated Area Burned", f"{area_pred:.2f} ha", "If fire occurs", delta_color="inverse")
                st.warning(f"High risk of fire detected! Estimated spread is **{area_pred:.2f} hectares**.")
            else:
                res_col2.metric("Estimated Risk", "Low", "Favorable conditions", delta_color="normal")
                st.success("Low risk of fire occurrence based on current parameters.")
                
            st.info("Remember: The metrics are calculated based on Montesinho Nature Park, Portugal.")
        except Exception as e:
            st.error(f"Error making prediction: {e}")
